#!/usr/bin/env python3
"""Expanding-date V85 backtest; independent horse data, honest paired ATG benchmark.

Research only. Each prediction is generated by a model trained strictly on
earlier race dates. Comparisons use identical races and only near-complete
results and complete retrospective betting pools.
"""
from __future__ import annotations

import datetime as dt
import json
import math
import pathlib
import statistics
import sys

from scripts.train_historical_pilot import FEATURES, normalized_per_race, evaluate

ROOT=pathlib.Path(__file__).resolve().parents[1]
INPUT=ROOT/"research/historical_pilot_2026.json"
OUTPUT=ROOT/"research/walkforward_report_2026.json"
RELATIVE_FEATURES=("post_field_ratio","form_percentile","wins_percentile",
                   "recent_km_percentile","purse_percentile")
MIN_TRAIN_STARTERS=160
MIN_TRAIN_DATES=4
MIN_HELDOUT_DATES=2


def rank_pct(value, samples, lower_is_better=False):
    if value is None or not samples or len(samples)<3:
        return None
    others=[v for v in samples if v is not None and math.isfinite(v)]
    if len(others)<3:
        return None
    below=sum(v<value for v in others)
    tied=sum(v==value for v in others)
    percentile=(below+tied/2)/len(others)
    return round(1-percentile if lower_is_better else percentile,4)


def enriched_matrix(rows):
    """Only relative past-performance features; never outcome or betting data."""
    import numpy as np
    grouped={}
    for i,r in enumerate(rows):
        grouped.setdefault(r["raceId"],[]).append(i)
    features=[None]*len(rows)
    for _,indices in grouped.items():
        info=[rows[i]["prestartFeatures"] for i in indices]
        get=lambda key:[v.get(key) for v in info if v.get(key) is not None]
        form=get("form_place_mean")
        win=get("win5")
        km=get("km_median")
        purse=get("past_purse_log")
        for i in indices:
            x=rows[i]["prestartFeatures"]
            post=x.get("post")
            field=x.get("field")
            relative=[
                min(1.5,post/field) if post is not None and field and field>0 else None,
                rank_pct(x.get("form_place_mean"),form,lower_is_better=True),
                rank_pct(x.get("win5"),win),
                rank_pct(x.get("km_median"),km,lower_is_better=True),
                rank_pct(x.get("past_purse_log"),purse),
            ]
            features[i]=[(float(x[k]) if x.get(k) is not None else float("nan")) for k in FEATURES]+[
                float(v) if v is not None else float("nan") for v in relative
            ]
    return np.asarray(features,dtype="float64")


def clean_paired(groups):
    """Do not renormalize the final pool over a truncated result field."""
    eligible={}
    for rid,items in groups.items():
        if len(items)<6 or sum(x["winner"] for x in items)!=1:
            continue
        if not all(isinstance(x.get("resultCoverage"),(float,int)) and x["resultCoverage"]>=0.999
                   for x in items):
            continue
        market=[x.get("marketFinalPct") for x in items]
        if any(v is None or not isinstance(v,(float,int)) or v<0 for v in market):
            continue
        if not 95<=sum(market)<=105:
            continue
        eligible[rid]=items
    return eligible


def produce():
    import numpy as np
    from xgboost import XGBClassifier
    doc=json.loads(INPUT.read_text())
    rows=doc.get("rows",[])
    dates=sorted({r["date"] for r in rows})
    if len(dates)<MIN_TRAIN_DATES+MIN_HELDOUT_DATES:
        raise RuntimeError("Too few independent dates for expanding-origin evaluation")
    out={};folds=[];total_training=set()
    for i,date in enumerate(dates):
        if i<MIN_TRAIN_DATES:
            continue
        training=[r for r in rows if r["date"]<date]
        holdout=[r for r in rows if r["date"]==date]
        if len(training)<MIN_TRAIN_STARTERS or len(holdout)<6:
            continue
        # All horses in a date are held out together, never same-date training.
        if max(r["date"] for r in training)>=date:
            raise AssertionError("Future leak detected")
        model=XGBClassifier(
            n_estimators=120,max_depth=3,learning_rate=0.055,
            subsample=0.85,colsample_bytree=0.85,
            reg_lambda=5,objective="binary:logistic",
            eval_metric="logloss",tree_method="hist",random_state=214,n_jobs=2)
        model.fit(enriched_matrix(training),
                  np.asarray([r["winner"] for r in training],dtype="int32"))
        prediction=model.predict_proba(enriched_matrix(holdout))[:,1]
        fold_groups={}
        for row,p in zip(holdout,prediction):
            candidate={**row,"pred":float(p)}
            fold_groups.setdefault(row["raceId"],[]).append(candidate)
        fold_metrics=evaluate(fold_groups,"pred")
        paired=clean_paired(fold_groups)
        paired_model=evaluate(paired,"pred")
        paired_market=evaluate(paired,"marketFinalPct",market=True)
        if fold_metrics["races"]<1:
            continue
        folds.append({
            "date":date,"trainUntil":max(r["date"] for r in training),
            "trainedDates":len({r["date"] for r in training}),
            "trainStarts":len(training),
            "testMetrics":fold_metrics,
            "pairedRaces":len(paired),
            "pairedModel":paired_model,
            "pairedMarket":paired_market,
        })
        total_training.add(date)
        out.update(fold_groups)
    if len(folds)<MIN_HELDOUT_DATES or sum(f["testMetrics"]["races"] for f in folds)<12:
        raise RuntimeError("Insufficient tested dates or races; no report published")
    paired=clean_paired(out)
    metrics=evaluate(out,"pred")
    pm=evaluate(paired,"pred")
    market=evaluate(paired,"marketFinalPct",market=True)
    report={
        "reportType":"EXPANDING_CHRONOLOGICAL_BACKTEST_NOT_VALIDATED",
        "generatedAt":dt.datetime.now(dt.timezone.utc).isoformat(),
        "sourceRaceCount":doc.get("raceCount"),"sourceStarts":doc.get("starterCount"),
        "sourceDates":len(dates),
        "folds":folds,
        "testMetrics":metrics,
        "strictPairedModel":pm,
        "strictPairedMarket":market,
        "strictPairedCount":len(paired),
        "excludedFromMarketComparison":metrics["races"]-len(paired),
        "features":[*FEATURES,*RELATIVE_FEATURES],
        "method":"Expanding-origin model re-fit before each held-out date, trained on strictly earlier dates, with race-relative prestart features.",
        "limitations":"Exploratory, few races, some training race results incomplete, history sample covers selected dates only. Final-pool market is not a prestart timestamp. No validated win probabilities, Benter blend or profit forecast.",
    }
    current=json.loads(OUTPUT.read_text()) if OUTPUT.exists() else {}
    comparable=lambda x:{k:v for k,v in x.items() if k!="generatedAt"}
    if comparable(current)==comparable(report):
        print("WALKFORWARD unchanged: no new commit");return
    OUTPUT.parent.mkdir(parents=True,exist_ok=True)
    OUTPUT.write_text(json.dumps(report,indent=2,ensure_ascii=False)+"\n")
    print("WALKFORWARD",len(folds),"folds",metrics["races"],"tested races",
          "strict benchmark",len(paired),"model",pm,"market",market,flush=True)


if __name__=="__main__":
    try:
        produce()
    except (ImportError,RuntimeError,ValueError,AssertionError) as exc:
        print("WALKFORWARD NOT READY:",type(exc).__name__,str(exc),flush=True)
        sys.exit(1)
